CREATE TABLE IF NOT EXISTS public.simulation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_name TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    arrival_rate REAL NOT NULL,
    doctor_mu REAL NOT NULL,
    num_doctors INT NOT NULL,
    nurse_mu REAL NOT NULL,
    num_nurses INT NOT NULL,
    num_beds INT,
    sim_hours REAL NOT NULL,
    doctor_rho REAL,
    doctor_wq_min REAL,
    doctor_w_min REAL,
    doctor_lq REAL,
    doctor_l REAL,
    status TEXT NOT NULL CHECK (status IN ('OK', 'WARNING', 'UNSTABLE'))
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.simulation_runs ENABLE ROW LEVEL SECURITY;

-- Allow public read access
CREATE POLICY "Allow public read access"
ON public.simulation_runs FOR SELECT
TO anon, authenticated
USING (true);

-- Allow public insert access
CREATE POLICY "Allow public insert access"
ON public.simulation_runs FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Allow public delete access
CREATE POLICY "Allow public delete access"
ON public.simulation_runs FOR DELETE
TO anon, authenticated
USING (true);
