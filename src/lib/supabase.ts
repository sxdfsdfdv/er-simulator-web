const STORAGE_KEY_SCENARIOS = 'er_simulator_scenarios';
const STORAGE_KEY_CONFIG = 'er_simulator_supabase_cfg';

export interface SupabaseConfig {
  url: string;
  anonKey: string;
}

export function getStoredSupabaseConfig(): SupabaseConfig {
  const DEFAULT_URL = 'https://syiautycpwumhpsjxnim.supabase.co';
  const DEFAULT_KEY = 'sb_publishable_JTzpLR81pzOcpYQMfFhcgQ_ueCeIw7y';

  if (typeof window === 'undefined') {
    return {
      url: process.env.NEXT_PUBLIC_SUPABASE_URL || DEFAULT_URL,
      anonKey: process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || DEFAULT_KEY,
    };
  }

  const stored = localStorage.getItem(STORAGE_KEY_CONFIG);
  if (stored) {
    try {
      const parsed = JSON.parse(stored);
      if (parsed.url && parsed.anonKey) return parsed;
    } catch {}
  }

  return {
    url: process.env.NEXT_PUBLIC_SUPABASE_URL || DEFAULT_URL,
    anonKey: process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || DEFAULT_KEY,
  };
}

export function saveStoredSupabaseConfig(cfg: SupabaseConfig): void {
  if (typeof window !== 'undefined') {
    localStorage.setItem(STORAGE_KEY_CONFIG, JSON.stringify(cfg));
  }
}

export function getSupabaseClient(): SupabaseClient | null {
  const cfg = getStoredSupabaseConfig();
  if (cfg.url && cfg.anonKey) {
    try {
      return createClient(cfg.url, cfg.anonKey);
    } catch (e) {
      console.warn('Failed to initialize Supabase client:', e);
      return null;
    }
  }
  return null;
}

