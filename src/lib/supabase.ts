export interface TestResult {
  ok: boolean;
  message: string;
  tableMissing?: boolean;
}

export async function testSupabaseConnection(url: string, anonKey: string): Promise<TestResult> {
  const cleanUrl = (url || '').trim().replace(/\/$/, '');
  const cleanKey = (anonKey || '').trim();

  if (!cleanUrl || !cleanKey) {
    return { ok: false, message: 'Project URL과 API Key를 모두 입력해주세요.' };
  }

  if (cleanUrl.includes('supabase.com/dashboard')) {
    return {
      ok: false,
      message: '입력하신 주소는 대시보드 관리 URL입니다. Supabase 대시보드 좌측 ⚙️ Project Settings > Data API 에서 "https://[프로젝트ID].supabase.co" 형태의 Project URL을 복사해주세요.',
    };
  }

  if (!cleanUrl.startsWith('https://') && !cleanUrl.startsWith('http://')) {
    return {
      ok: false,
      message: 'Project URL은 https://[프로젝트ID].supabase.co 형식이어야 합니다.',
    };
  }

  try {
    const client = createClient(cleanUrl, cleanKey);
    const { data, error } = await client
      .from('simulation_runs')
      .select('*')
      .limit(1);

    if (error) {
      const msg = error.message || '';
      if (
        error.code === '42P01' ||
        error.code === 'PGRST204' ||
        error.code === 'PGRST205' ||
        msg.includes('does not exist') ||
        msg.includes('not found') ||
        msg.includes('relation')
      ) {
        return {
          ok: false,
          tableMissing: true,
          message: 'Supabase 서버 연결은 성공했습니다! 하지만 "simulation_runs" 테이블이 아직 없습니다. 아래 안내에 따라 SQL을 1회 실행해주세요.',
        };
      }
      return {
        ok: false,
        message: `연결 오류 (${error.code || 'FAIL'}): ${msg}`,
      };
    }

    return {
      ok: true,
      message: '🎉 Supabase 클라우드 데이터베이스에 성공적으로 연결되었습니다!',
    };
  } catch (err: any) {
    return {
      ok: false,
      message: `연결 실패: ${err?.message || '네트워크 상태나 URL/Key를 다시 확인해주세요.'}`,
    };
  }
}

